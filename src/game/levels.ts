/**
 * 스테이지 데이터.
 *
 * 맵은 가로 15칸 × 세로 12칸이다. 바깥 테두리 벽은 엔진이 자동으로 두르므로
 * 여기에는 안쪽만 적는다. 한 글자가 한 칸이다.
 *
 * | 글자 | 뜻 |
 * |---|---|
 * | `.` | 빈칸 |
 * | `#` | 단단한 벽 (마법으로 부술 수 없다) |
 * | `o` | 돌 블록 (마법이나 박치기로 부술 수 있다) |
 * | `P` | 멀린 시작 위치 |
 * | `K` `D` | 열쇠, 문 |
 * | `k` | 열쇠가 숨은 돌 블록 |
 * | `1`~`5` | 보석·불꽃 항아리·모래시계·종·룬이 숨은 돌 블록 |
 * | `$` `j` `h` `b` `r` | 보석, 불꽃 항아리, 모래시계, 종, 룬 |
 * | `g` `O` | 고블린, 오우거 (오우거는 앞을 막는 돌 블록을 부순다) |
 * | `w` | 위습 (가로로 날며 부딪힌 돌 블록을 부순다) |
 * | `s` | 스파크 (블록 표면을 따라 기어 다닌다) |
 * | `<` `>` | 가고일 (그쪽을 보고 불을 뱉는다) |
 * | `M` `m` | 거울 (고블린·위습을 계속 불러낸다) |
 *
 * 스테이지 이름과 힌트 문구는 `src/i18n.ts` 의 `stageN`, `hintN` 키에 있다.
 */

